    fun translate(text: String, language: AppLanguage): String {
        if (language != AppLanguage.Japanese) return text

        resendPattern.matchEntire(text)?.let { match ->
            return "再送 (${match.groupValues[1]})"
        }

        maxImagesPattern.matchEntire(text)?.let { match ->
            return "画像は最大${match.groupValues[1]}枚までアップロードできます。"
        }

        return japaneseMap[text] ?: text
    }
